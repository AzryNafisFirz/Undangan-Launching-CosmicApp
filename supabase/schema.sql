create table if not exists public.event_guests (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null check (char_length(trim(name)) between 2 and 100),
  company text,
  age integer check (age between 1 and 120),
  attendance text not null check (attendance in ('hadir', 'tidak_hadir', 'belum_pasti')),
  participant_type text not null default 'tamu' check (participant_type in ('tamu', 'investor')),
  message text not null check (char_length(trim(message)) between 1 and 1000),
  source_guest text
);

create table if not exists public.investors (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null check (char_length(trim(name)) between 2 and 100),
  company text,
  email text,
  phone text,
  interest text,
  message text
);

alter table public.event_guests enable row level security;
alter table public.investors enable row level security;

create policy "Public can submit guests"
  on public.event_guests for insert
  to anon, authenticated
  with check (true);

create policy "Public can read approved guestbook entries"
  on public.event_guests for select
  to anon, authenticated
  using (message is not null);

create policy "Public can submit investor interest"
  on public.investors for insert
  to anon, authenticated
  with check (true);

create index if not exists event_guests_created_at_idx on public.event_guests(created_at desc);
create index if not exists investors_created_at_idx on public.investors(created_at desc);
