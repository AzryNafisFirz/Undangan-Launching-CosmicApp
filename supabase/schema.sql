-- Supabase setup: jalankan di Dashboard -> SQL Editor.
-- Data RSVP (attendance/age) tersimpan di event_guests, tetapi hanya kolom
-- nama/perusahaan/pesan yang dapat dibaca publik untuk buku tamu.

create table if not exists public.event_guests (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null check (char_length(trim(name)) between 2 and 100),
  company text,
  age integer check (age between 1 and 120),
  attendance text not null check (attendance in ('hadir', 'tidak_hadir', 'belum_pasti')),
  message text not null check (char_length(trim(message)) between 1 and 1000)
);

-- Tambahkan kolom untuk pemasangan di database lama yang sudah punya event_guests.
alter table public.event_guests add column if not exists attendance text;
alter table public.event_guests add column if not exists age integer;

alter table public.event_guests enable row level security;

drop policy if exists "Public can submit guests" on public.event_guests;
create policy "Public can submit guests"
  on public.event_guests for insert
  to anon, authenticated
  with check (
    char_length(trim(name)) between 2 and 100
    and attendance in ('hadir', 'tidak_hadir', 'belum_pasti')
    and char_length(trim(message)) between 1 and 1000
    and (age is null or age between 1 and 120)
  );

drop policy if exists "Public can read approved guestbook entries" on public.event_guests;
create policy "Public can read guestbook entries"
  on public.event_guests for select
  to anon, authenticated
  using (true);

-- Jangan publikasikan RSVP/umur; anon hanya boleh membaca kolom buku tamu.
revoke all on public.event_guests from anon, authenticated;
grant insert (name, company, age, attendance, message) on public.event_guests to anon, authenticated;
grant select (name, company, message, created_at) on public.event_guests to anon, authenticated;
grant usage, select on sequence public.event_guests_id_seq to anon, authenticated;

create index if not exists event_guests_created_at_idx on public.event_guests(created_at desc);
