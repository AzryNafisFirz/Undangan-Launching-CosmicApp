-- Run in Supabase Dashboard -> SQL Editor.
-- RSVP/investor fields are stored in event_guests. Public book display is limited
-- to name, company, message and timestamp; attendance/age/type remain private.

create table if not exists public.event_guests (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null,
  company text,
  age integer,
  participant_type text not null default 'tamu',
  attendance text not null default 'belum_pasti',
  message text not null
);

-- Keep compatible with an existing guestbook table from an earlier setup.
alter table public.event_guests add column if not exists age integer;
alter table public.event_guests add column if not exists participant_type text not null default 'tamu';
alter table public.event_guests add column if not exists attendance text not null default 'belum_pasti';
alter table public.event_guests add column if not exists created_at timestamptz not null default now();

alter table public.event_guests enable row level security;

drop policy if exists "Public can submit guests" on public.event_guests;
create policy "Public can submit guests"
  on public.event_guests for insert to anon, authenticated
  with check (
    char_length(trim(name)) between 2 and 100
    and (age is null or age between 1 and 120)
    and participant_type in ('tamu', 'investor')
    and attendance in ('hadir', 'tidak_hadir', 'belum_pasti')
    and char_length(trim(message)) between 1 and 1000
  );

drop policy if exists "Public can read approved guestbook entries" on public.event_guests;
drop policy if exists "Public can read guestbook entries" on public.event_guests;
create policy "Public can read guestbook entries"
  on public.event_guests for select to anon, authenticated
  using (true);

-- Column grants prevent public visitors from reading RSVP, age, or participant type.
revoke all on public.event_guests from anon, authenticated;
grant insert (name, company, age, participant_type, attendance, message)
  on public.event_guests to anon, authenticated;
grant select (name, company, message, created_at)
  on public.event_guests to anon, authenticated;
grant usage, select on sequence public.event_guests_id_seq to anon, authenticated;

create index if not exists event_guests_created_at_idx
  on public.event_guests(created_at desc);
